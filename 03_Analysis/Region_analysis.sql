
---- Analyze sales, profit, quantity and profit margin by region
SELECT
    o.REGION,
    ROUND(SUM(oi.SALES), 2) AS TOTAL_SALES,--TOTOAL SLAES FOR EACH REGION
    ROUND(SUM(oi.PROFIT), 2) AS TOTAL_PROFIT,--TOTAL PROFIT FOR EACH REGION
    SUM(oi.QUANTITY) AS TOTAL_QUANTITY,--TOTAL UNITS SOLD IN EACH REGION
    ROUND(
        (SUM(oi.PROFIT) / NULLIF(SUM(oi.SALES), 0)) * 100,
        2
    ) AS PROFIT_MARGIN_PERCENT---PROFIT AS A PERCENTAGES SALES 
FROM ORDERS o
JOIN ORDER_ITEMS oi
    ON o.ORDER_ID = oi.ORDER_ID
GROUP BY o.REGION
ORDER BY TOTAL_SALES DESC;



