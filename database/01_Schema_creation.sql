    ROW_ID          NUMBER,
    ORDER_ID        VARCHAR2(30),
    ORDER_DATE      DATE,
    SHIP_DATE       DATE,
    SHIP_MODE       VARCHAR2(50),
    CUSTOMER_ID     VARCHAR2(30),
    CUSTOMER_NAME   VARCHAR2(200),
    SEGMENT         VARCHAR2(50),
    COUNTRY         VARCHAR2(100),
    CITY            VARCHAR2(100),
    STATE           VARCHAR2(100),
    POSTAL_CODE     NUMBER,
    REGION          VARCHAR2(50),
    PRODUCT_ID      VARCHAR2(50),
    CATEGORY        VARCHAR2(100),
    SUB_CATEGORY    VARCHAR2(100),
    PRODUCT_NAME    VARCHAR2(500),
    SALES           NUMBER(18,4),
    QUANTITY        NUMBER,
    DISCOUNT        NUMBER(10,4),
    PROFIT          NUMBER(18,4)
);


-- customer table creation
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID     VARCHAR2(30) PRIMARY KEY,
    CUSTOMER_NAME   VARCHAR2(200) NOT NULL,
    SEGMENT         VARCHAR2(50),
    COUNTRY         VARCHAR2(100),
    CITY            VARCHAR2(100),
    STATE           VARCHAR2(100),
    REGION          VARCHAR2(50)
);


-- product table creation

CREATE TABLE PRODUCTS (
    PRODUCT_ID     VARCHAR2(50) PRIMARY KEY,
    PRODUCT_NAME   VARCHAR2(500) NOT NULL,
    CATEGORY       VARCHAR2(100),
    SUB_CATEGORY   VARCHAR2(100)
);


-- orders table creation
CREATE TABLE ORDERS (
    ORDER_ID     VARCHAR2(30) PRIMARY KEY,
    CUSTOMER_ID  VARCHAR2(30) NOT NULL,
    ORDER_DATE   DATE NOT NULL,
    SHIP_DATE    DATE NOT NULL,
    SHIP_MODE    VARCHAR2(50),
    REGION       VARCHAR2(50),

    CONSTRAINT FK_ORDERS_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMERS(CUSTOMER_ID),

    CONSTRAINT CK_ORDER_DATES
        CHECK (SHIP_DATE >= ORDER_DATE)
);

-- creation of order_item table

CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER PRIMARY KEY,
    ORDER_ID      VARCHAR2(30) NOT NULL,
    PRODUCT_ID    VARCHAR2(50) NOT NULL,
    QUANTITY      NUMBER NOT NULL,
    SALES         NUMBER(18,4) NOT NULL,
    DISCOUNT      NUMBER(10,4) NOT NULL,
    PROFIT        NUMBER(18,4) NOT NULL,

    CONSTRAINT FK_ORDER_ITEMS_ORDER
        FOREIGN KEY (ORDER_ID)
        REFERENCES ORDERS(ORDER_ID),

    CONSTRAINT FK_ORDER_ITEMS_PRODUCT
        FOREIGN KEY (PRODUCT_ID)
        REFERENCES PRODUCTS(PRODUCT_ID),

    CONSTRAINT CK_ORDER_ITEMS_QTY
        CHECK (QUANTITY > 0),

    CONSTRAINT CK_ORDER_ITEMS_SALES
        CHECK (SALES >= 0),

    CONSTRAINT CK_ORDER_ITEMS_DISCOUNT
        CHECK (DISCOUNT BETWEEN 0 AND 1)
);


-- rejected_record table creation 
CREATE TABLE REJECTED_RECORDS (
    REJECT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ROW_ID          NUMBER,
    ORDER_ID        VARCHAR2(30),
    REASON          VARCHAR2(500),
    REJECTED_DATE   DATE DEFAULT SYSDATE
);


-- etl audit table creation


CREATE TABLE ETL_AUDIT (
    AUDIT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROCESS_NAME   VARCHAR2(100) NOT NULL,
    START_TIME     TIMESTAMP DEFAULT SYSTIMESTAMP,
    END_TIME       TIMESTAMP,
    ROWS_PROCESSED NUMBER,
    STATUS         VARCHAR2(20),
    ERROR_MESSAGE  VARCHAR2(1000)
);